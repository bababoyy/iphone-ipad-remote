#!/usr/bin/env python3
"""Validate iphone-app/layout.json and embed it as a Swift string constant
(iphone-app/LayoutData.generated.swift), so the IPA needs no bundle resource."""
import json, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import gamepad_layout as gl

spec = gl.load()  # raises on an invalid layout
compact = json.dumps(spec, ensure_ascii=False, separators=(",", ":"))
# Raw string ##"..."##: hex colours contain '"#', so use two '#'. Only '"##'
# would end it and only '\\##' would start an escape.
assert '"##' not in compact and "\\##" not in compact, "layout.json breaks the Swift raw string"
out = gl.ROOT / "iphone-app/LayoutData.generated.swift"
out.write_text(
    "// Generated by scripts/embed_layout.py from iphone-app/layout.json. Do not edit.\n"
    f'let kGamepadLayoutJSON = ##"{compact}"##\n', encoding="utf-8")
print(f"Embedded layout.json ({len(compact)} bytes, {len(spec['controls'])} controls)")
